// 日本語の文字の「比較用」の正規化
//
// Word やブラウザで作った日本語PDFでは、見た目は同じでも別の文字（部首の文字）が使われていることがある。
//   例：「長期」の「長」が「⻑」（CJK部首補助）、「山田」の「山」が「⼭」（康熙部首）
// このままだと検索や照合で一致しないため、比較用の文字列でだけ通常の漢字に置き換える。
// ※ 保存する元の文字（マーカーした文章など）は変えない。

// CJK部首補助（U+2E80〜U+2EFF）のうち、論文でよく現れる文字と通常の漢字の対応表
// （康熙部首 U+2F00〜U+2FD5 は NFKC 正規化で通常の漢字になるため、表に含めない）
const RADICAL_SUPPLEMENT_MAP = {
  '⺠': '民', '⺢': '水', '⺣': '火', '⺤': '爪', '⺥': '爪', '⺦': '丬', '⺧': '牛', '⺩': '王',
  '⺫': '目', '⺬': '示', '⺭': '示', '⺮': '竹', '⺯': '糸', '⺰': '糸', '⺲': '罒', '⺳': '网',
  '⺶': '羊', '⺷': '羊', '⺹': '耂', '⺼': '肉', '⺾': '艸', '⺿': '艸', '⻀': '艸', '⻁': '虎',
  '⻂': '衣', '⻄': '西', '⻅': '見', '⻆': '角', '⻇': '角', '⻈': '言', '⻉': '貝', '⻋': '車',
  '⻏': '阝', '⻑': '長', '⻒': '長', '⻔': '門', '⻖': '阝', '⻘': '青', '⻙': '韋', '⻚': '頁',
  '⻛': '風', '⻜': '飛', '⻝': '食', '⻞': '食', '⻟': '食', '⻠': '食', '⻢': '馬', '⻣': '骨',
  '⻤': '鬼', '⻥': '魚', '⻦': '鳥', '⻧': '鹵', '⻨': '麦', '⻩': '黄', '⻪': '黽', '⻫': '斉',
  '⻬': '斉', '⻭': '歯', '⻮': '歯', '⻯': '竜', '⻰': '竜', '⻱': '龜', '⻲': '亀', '⻳': '亀',
};
const RADICAL_PATTERN = new RegExp(`[${Object.keys(RADICAL_SUPPLEMENT_MAP).join('')}]`, 'g');

/**
 * 比較用に文字をそろえる。
 * NFKC：全角英数字→半角、半角カナ→全角、康熙部首→通常の漢字 など
 * そのあと、CJK部首補助の文字を通常の漢字に置き換える。
 */
export function normalizeCjk(text) {
  return String(text ?? '')
    .normalize('NFKC')
    .replace(RADICAL_PATTERN, (char) => RADICAL_SUPPLEMENT_MAP[char]);
}

/** 日本語の文字（ひらがな・カタカナ・漢字）の割合（0〜1） */
export function japaneseRatio(text) {
  const chars = String(text ?? '').replace(/\s/g, '');
  if (chars.length === 0) return 0;
  const japanese = chars.match(/[぀-ヿ㐀-鿿豈-﫿]/g)?.length ?? 0;
  return japanese / chars.length;
}

/** 照合用：正規化したうえで、空白・記号を取り除き、小文字にする */
export function compactForMatch(text) {
  return normalizeCjk(text)
    .toLowerCase()
    .replace(/[\s\p{P}\p{S}]/gu, '');
}
